#!/usr/bin/env python3
# INDEX: WAF/CDN passive fingerprint + block-vs-crash response classifier | all
"""WAF/CDN awareness for the black-box detector (stdlib only).

Two jobs, so the detector never misreads a WAF block as the bug firing:

  fingerprint(headers, server=None) -> vendor|None
      Passive: name a WAF/CDN from response headers (CF-RAY, X-Sucuri-ID,
      X-Amz-Cf-Id, X-Iinfo, Server: cloudflare/akamaighost/..., etc.).

  classify(status, headers, body) -> verdict
      What a response really is, for a liveness/crash decision:
        "ok"          HTTP 200 (serving)
        "blocked"     WAF/CDN refused the request (403/406, or a block body)
        "ratelimited" 429, or 503 with Retry-After
        "challenge"   interstitial JS/CAPTCHA page (cf-challenge, "Just a moment")
        "down"        no response / transport failure (status is None)
        "other"       any other status (e.g. a PHP 500/502 from our own probe)
      Only "down" (and an app/own 5xx classified "other") is a worker-liveness
      signal. "blocked"/"ratelimited"/"challenge" are the WAF -- NOT the bug.

is_interference(verdict) is True for the three WAF verdicts, so a caller can
refuse to upgrade to VULNERABLE and suggest --waf-bypass instead.
"""
from __future__ import annotations

# Header name (lowercased) -> vendor; presence of the header alone is the signal.
_HEADER_VENDORS = {
    "cf-ray": "Cloudflare", "cf-cache-status": "Cloudflare", "cf-mitigated": "Cloudflare",
    "x-sucuri-id": "Sucuri", "x-sucuri-cache": "Sucuri",
    "x-amz-cf-id": "AWS CloudFront", "x-amzn-waf-action": "AWS WAF",
    "x-akamai-transformed": "Akamai", "akamai-grn": "Akamai",
    "x-iinfo": "Imperva Incapsula", "x-cdn": "Imperva Incapsula",
    "x-sourcefire": "Cisco", "x-protected-by": "Sqreen",
}
# Substring (lowercased) found in the Server header -> vendor.
_SERVER_VENDORS = (
    ("cloudflare", "Cloudflare"), ("akamaighost", "Akamai"), ("sucuri", "Sucuri"),
    ("awselb", "AWS ELB"), ("incapsula", "Imperva Incapsula"), ("big-ip", "F5 BIG-IP"),
    ("barracuda", "Barracuda"), ("mod_security", "ModSecurity"), ("modsecurity", "ModSecurity"),
    ("airlock", "Airlock"), ("nginx-wallarm", "Wallarm"), ("fortiweb", "FortiWeb"),
)
# Set-Cookie / body substrings (lowercased) -> vendor.
_COOKIE_VENDORS = (
    ("incap_ses", "Imperva Incapsula"), ("visid_incap", "Imperva Incapsula"),
    ("__cfduid", "Cloudflare"), ("__cf_bm", "Cloudflare"),
)
# Body markers (lowercased) of a block/challenge interstitial.
_CHALLENGE_MARKERS = (
    b"__cf_chl", b"cf-challenge", b"/cdn-cgi/challenge-platform", b"just a moment",
    b"checking your browser", b"attention required", b"cf_chl_opt",
    b"request unsuccessful. incapsula", b"incident id", b"please enable cookies",
)
_BLOCK_MARKERS = (
    b"access denied", b"request blocked", b"this error was generated by mod_security",
    b"mod_security", b"forbidden", b"blocked by", b"web application firewall",
)


def _ci(headers):
    return {str(k).lower(): str(v) for k, v in (headers or {}).items()}


def fingerprint(headers, server=None):
    """Name a WAF/CDN from response headers, or None. `server` overrides the
    Server header if the caller already parsed it."""
    h = _ci(headers)
    for name, vendor in _HEADER_VENDORS.items():
        if name in h:
            return vendor
    srv = (server if server is not None else h.get("server", "")).lower()
    for sub, vendor in _SERVER_VENDORS:
        if sub in srv:
            return vendor
    cookie = h.get("set-cookie", "").lower()
    for sub, vendor in _COOKIE_VENDORS:
        if sub in cookie:
            return vendor
    return None


def _has(body, markers):
    if not body:
        return False
    b = body.lower() if isinstance(body, (bytes, bytearray)) else str(body).lower().encode()
    return any(m in b for m in markers)


def classify(status, headers, body):
    """Classify a response for a liveness/crash decision. See module docstring."""
    if status is None:
        return "down"
    h = _ci(headers)
    if _has(body, _CHALLENGE_MARKERS):
        return "challenge"
    if status == 429 or (status == 503 and "retry-after" in h):
        return "ratelimited"
    if status in (401, 403, 406):
        return "blocked"
    if status == 200:
        return "ok"
    if status in (400, 405, 501) and _has(body, _BLOCK_MARKERS):
        return "blocked"
    return "other"


def is_interference(verdict):
    """True iff the verdict is a WAF/CDN interfering (not a worker-liveness signal)."""
    return verdict in ("blocked", "ratelimited", "challenge")


def retry_after(headers):
    """Retry-After header value as int seconds, or None."""
    v = _ci(headers).get("retry-after")
    if v and v.isdigit():
        return int(v)
    return None
